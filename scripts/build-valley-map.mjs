import { writeFile } from "node:fs/promises";
import { geoAlbers, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const WIDTH = 1000;
const HEIGHT = 560;
const PAD = 14;
const STATES = {
  "21": "Kentucky",
  "39": "Ohio",
  "42": "Pennsylvania",
  "54": "West Virginia",
};

const atlasUrl = "https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/counties-10m.json";
const namesUrl =
  "https://www2.census.gov/geo/docs/reference/codes2020/national_county2020.txt";

const atlas = await (await fetch(atlasUrl)).json();
const namesText = await (await fetch(namesUrl)).text();
const names = new Map();

for (const line of namesText.split(/\r?\n/).slice(1)) {
  if (!line.trim()) continue;
  const parts = line.split("|");
  if (parts.length < 5) continue;
  const fips = `${parts[1]}${parts[2]}`;
  names.set(fips, parts[4]);
}

const countyFeatures = feature(atlas, atlas.objects.counties).features.filter((item) =>
  STATES[String(item.id).padStart(5, "0").slice(0, 2)],
);
const stateFeatures = feature(atlas, atlas.objects.states).features.filter(
  (item) => STATES[String(item.id).padStart(2, "0")],
);

const projection = geoAlbers()
  .parallels([37, 41.5])
  .rotate([82.5, 0])
  .fitExtent(
    [
      [PAD, PAD],
      [WIDTH - PAD, HEIGHT - PAD],
    ],
    { type: "FeatureCollection", features: stateFeatures },
  );

const path = geoPath(projection);
path.digits(1);

function fipsOf(id, width) {
  return String(id).padStart(width, "0");
}

const counties = countyFeatures
  .map((item) => {
    const fips = fipsOf(item.id, 5);
    const d = path(item);
    if (!d) return null;
    const centroid = path.centroid(item);
    if (!Number.isFinite(centroid[0]) || !Number.isFinite(centroid[1])) return null;
    return {
      fips,
      state: STATES[fips.slice(0, 2)],
      name: names.get(fips) ?? `County ${fips}`,
      x: Number(centroid[0].toFixed(1)),
      y: Number(centroid[1].toFixed(1)),
      d,
    };
  })
  .filter(Boolean)
  .sort((a, b) => a.fips.localeCompare(b.fips));

const states = stateFeatures
  .map((item) => {
    const fips = fipsOf(item.id, 2);
    const d = path(item);
    if (!d) return null;
    return { fips, name: STATES[fips], d };
  })
  .filter(Boolean)
  .sort((a, b) => a.fips.localeCompare(b.fips));

const columbus = projection([-82.99, 39.96]);
if (!columbus || columbus[0] < 0 || columbus[0] > WIDTH || columbus[1] < 0 || columbus[1] > HEIGHT) {
  throw new Error(`Columbus projected outside the map: ${columbus}`);
}

const scale = projection.scale();
const translate = projection.translate();
const body = `// Generated by scripts/build-valley-map.mjs
// County and state outlines: US Census cartographic boundary, us-atlas 10m.
// Local SVG only. No map tile service.

export const VALLEY_WIDTH = ${WIDTH};
export const VALLEY_HEIGHT = ${HEIGHT};
export const VALLEY_PARALLELS = [37, 41.5] as const;
export const VALLEY_ROTATE = [82.5, 0] as const;
export const VALLEY_SCALE = ${scale};
export const VALLEY_TRANSLATE = [${translate[0]}, ${translate[1]}] as const;

export type ValleyCounty = {
  fips: string;
  state: "Kentucky" | "Ohio" | "Pennsylvania" | "West Virginia";
  name: string;
  x: number;
  y: number;
  d: string;
};

export type ValleyStateShape = {
  fips: string;
  name: "Kentucky" | "Ohio" | "Pennsylvania" | "West Virginia";
  d: string;
};

export const valleyCounties: ValleyCounty[] = ${JSON.stringify(counties)};

export const valleyStates: ValleyStateShape[] = ${JSON.stringify(states)};
`;

await writeFile(new URL("../src/lib/valley-map-data.ts", import.meta.url), body);
console.log(
  `counties ${counties.length}, states ${states.length}, scale ${scale.toFixed(2)}, columbus ${columbus.map((n) => n.toFixed(1)).join(",")}`,
);
